// Builds src/ui/emojiData.ts, the full emoji list for the chat picker, from Unicode's emoji-test.txt
// (https://unicode.org/Public/emoji/15.1/emoji-test.txt). Usage: node scripts/gen-emoji.mjs <emoji-test.txt>
// Keeps fully-qualified emoji up to MAX_VERSION, so phones a few years old can draw them all, and
// leaves out skin-tone and hair variants and the bare components, which would crowd the grid.
import { readFileSync, writeFileSync } from 'node:fs';

const MAX_VERSION = 15.0;
const SKIN = /[\u{1F3FB}-\u{1F3FF}]/u;
const GROUPS = {
  'Smileys & Emotion': ['smileys', 'Smileys', '😀'],
  'People & Body': ['people', 'People', '👋'],
  'Animals & Nature': ['nature', 'Animals & nature', '🐶'],
  'Food & Drink': ['food', 'Food & drink', '🍔'],
  'Travel & Places': ['travel', 'Travel & places', '🚗'],
  Activities: ['activities', 'Activities', '⚽'],
  Objects: ['objects', 'Objects', '💡'],
  Symbols: ['symbols', 'Symbols', '❤️'],
  Flags: ['flags', 'Flags', '🏁'],
};

const src = process.argv[2];
if (!src) throw new Error('Usage: node scripts/gen-emoji.mjs <emoji-test.txt>');
const groups = [];
let group = null;
for (const line of readFileSync(src, 'utf8').split('\n')) {
  const g = line.match(/^# group: (.+)$/);
  if (g) {
    const meta = GROUPS[g[1]];
    group = meta ? { id: meta[0], label: meta[1], icon: meta[2], emoji: [] } : null;
    if (group) groups.push(group);
    continue;
  }
  const m = line.match(/^[0-9A-F ]+; fully-qualified\s+# (\S+) E(\d+\.\d+) (.+)$/);
  if (!m || !group || Number(m[2]) > MAX_VERSION || SKIN.test(m[1])) continue;
  if (/: (red hair|curly hair|white hair|bald|beard)$/.test(m[3])) continue;
  group.emoji.push([m[1], m[3].replace(/^flag: /, 'flag ')]);
}

const body = groups
  .map((g) => `  {\n    id: '${g.id}',\n    label: '${g.label}',\n    icon: '${g.icon}',\n    emoji: [\n${g.emoji.map(([e, n]) => `      ['${e}', ${JSON.stringify(n)}],`).join('\n')}\n    ],\n  },`)
  .join('\n');
writeFileSync(
  new URL('../src/ui/emojiData.ts', import.meta.url),
  `// Generated by scripts/gen-emoji.mjs from Unicode emoji-test.txt; do not edit by hand.\n// Loaded only when someone opens the emoji picker.\n\nexport interface EmojiGroup {\n  id: string;\n  label: string;\n  icon: string;\n  /** [emoji, name] */\n  emoji: [string, string][];\n}\n\nexport const EMOJI_GROUPS: EmojiGroup[] = [\n${body}\n];\n`,
);
